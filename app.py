import os
import json
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import streamlit as st

st.set_page_config(
    page_title="Electricity Consumption Forecasting",
    page_icon="⚡",
    layout="wide"
)

# Root directory paths
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATASET_DIR = os.path.join(BASE_DIR, "datasets")
MODELS_DIR = os.path.join(BASE_DIR, "models")
OUTPUTS_DIR = os.path.join(BASE_DIR, "outputs")

SERIES_CSV_PATH = os.path.join(DATASET_DIR, "selected_series.csv")
INFO_JSON_PATH = os.path.join(OUTPUTS_DIR, "dataset_info.json")
METRICS_JSON_PATH = os.path.join(OUTPUTS_DIR, "metrics.json")
FORECAST_CSV_PATH = os.path.join(OUTPUTS_DIR, "forecast_24h.csv")
ACTUAL_VS_PRED_PLOT = os.path.join(OUTPUTS_DIR, "actual_vs_predicted.png")
LOSS_PLOT_PATH = os.path.join(OUTPUTS_DIR, "loss_plot.png")
FORECAST_PLOT_PATH = os.path.join(OUTPUTS_DIR, "forecast_24h.png")

# Sidebar
st.sidebar.title("⚡ Navigation")
st.sidebar.markdown("### Electricity Consumption Forecasting")
st.sidebar.info("Built with TensorFlow/Keras & Streamlit for NNDL Mini-Project.")

# Disclaimer Banner
st.warning("⚠️ **Notice:** Predictions displayed in this dashboard are generated using pre-trained neural network models trained on historical archived electricity data (Monash Monash/UCI Electricity Hourly Dataset). They do not represent a live real-time electricity feed.")

st.title("⚡ Electricity Consumption Forecasting Using Neural Networks")

# Load artifacts
@st.cache_data
def load_dataset_info():
    if os.path.exists(INFO_JSON_PATH):
        with open(INFO_JSON_PATH) as f:
            return json.load(f)
    return None

@st.cache_data
def load_metrics():
    if os.path.exists(METRICS_JSON_PATH):
        with open(METRICS_JSON_PATH) as f:
            return json.load(f)
    return None

@st.cache_data
def load_forecast_data():
    if os.path.exists(FORECAST_CSV_PATH):
        return pd.read_csv(FORECAST_CSV_PATH)
    return None

@st.cache_data
def load_historical_series():
    if os.path.exists(SERIES_CSV_PATH):
        df = pd.read_csv(SERIES_CSV_PATH)
        df['timestamp'] = pd.to_datetime(df['timestamp'])
        return df
    return None

info = load_dataset_info()
metrics = load_metrics()
forecast_df = load_forecast_data()
historical_df = load_historical_series()

# Overview Metrics Row
if metrics and info:
    col1, col2, col3, col4 = st.columns(4)
    col1.metric("Series ID", info.get("series_id", "T1"))
    col2.metric("MLP Test MAE", f"{metrics.get('mlp_test_mae', 0):.2f} kW")
    col3.metric("Baseline Test MAE", f"{metrics.get('naive_baseline_mae', 0):.2f} kW")
    col4.metric("24h Forecast MAE", f"{metrics.get('forecast_24h_mae', 0):.2f} kW")

st.markdown("---")

# Main Dashboard Tabs
tab1, tab2, tab3, tab4 = st.tabs(["📈 24-Hour Forecast", "📊 Actual vs Predicted", "📉 Training & Metrics", "🧠 Architecture & Methodology"])

with tab1:
    st.subheader("🔮 24-Hour Ahead Iterative Consumption Forecast")
    st.write("Below is the 24-hour forward iterative electricity consumption prediction generated by feeding model outputs step-by-step.")

    if forecast_df is not None:
        fig, ax = plt.subplots(figsize=(10, 4.5))
        ax.plot(forecast_df["hour_ahead"], forecast_df["actual_consumption"], marker='o', label="Actual Consumption", color="black")
        ax.plot(forecast_df["hour_ahead"], forecast_df["predicted_consumption"], marker='s', label="MLP 24h Iterative Forecast", color="red", linestyle="--")
        ax.set_title("Next 24 Hours Electricity Forecast (kW)")
        ax.set_xlabel("Forecast Horizon (Hours Ahead)")
        ax.set_ylabel("Consumption (kW)")
        ax.set_xticks(range(1, 25))
        ax.legend()
        ax.grid(True)
        st.pyplot(fig)

        st.subheader("📋 24-Hour Forecast Table")
        st.dataframe(forecast_df, use_container_width=True)
    else:
        st.error("Forecast data not available. Please run the evaluation step.")

with tab2:
    st.subheader("📊 Historical Consumption & Test Set Comparison")

    if historical_df is not None:
        st.write("##### Historical Electricity Consumption Time Series")
        fig_hist, ax_hist = plt.subplots(figsize=(12, 4))
        ax_hist.plot(historical_df["timestamp"], historical_df["consumption"], color="teal", linewidth=0.8)
        ax_hist.set_title("Full Historical Consumption Series")
        ax_hist.set_xlabel("Timestamp")
        ax_hist.set_ylabel("Consumption (kW)")
        ax_hist.grid(True)
        st.pyplot(fig_hist)

    if os.path.exists(ACTUAL_VS_PRED_PLOT):
        st.write("##### Held-Out Test Set: MLP Model vs Naive Baseline (t-24)")
        st.image(ACTUAL_VS_PRED_PLOT, use_container_width=True)

with tab3:
    st.subheader("📉 Model Training Loss & Quantitative Evaluation")
    col_loss, col_table = st.columns([1, 1])

    with col_loss:
        st.write("##### Training & Validation Loss (MSE)")
        if os.path.exists(LOSS_PLOT_PATH):
            st.image(LOSS_PLOT_PATH, use_container_width=True)

    with col_table:
        st.write("##### Model Performance Comparison")
        if metrics:
            comp_data = {
                "Model / Baseline": ["MLP Neural Network", "Naive Baseline (t-24)", "24-Hour Iterative Forecast"],
                "MAE (kW)": [
                    f"{metrics.get('mlp_test_mae', 0):.2f}",
                    f"{metrics.get('naive_baseline_mae', 0):.2f}",
                    f"{metrics.get('forecast_24h_mae', 0):.2f}"
                ],
                "RMSE (kW)": [
                    f"{metrics.get('mlp_test_rmse', 0):.2f}",
                    f"{metrics.get('naive_baseline_rmse', 0):.2f}",
                    f"{metrics.get('forecast_24h_rmse', 0):.2f}"
                ]
            }
            st.table(pd.DataFrame(comp_data))

            st.markdown("""
            **Key Insights:**
            - The **MLP Neural Network** achieves lower MAE and RMSE compared to the Naive Baseline on single-step prediction.
            - Iterative 24-step forecasting effectively captures day-ahead daily consumption patterns and periodicity.
            """)

with tab4:
    st.subheader("🧠 Model Architecture & Methodology Details")
    st.markdown("""
    ### Neural Network Architecture
    - **Model Type:** Multilayer Perceptron (MLP)
    - **Input Vector:** 168 past hourly observations (7 days × 24 hours)
    - **Dense Layer 1:** 128 units, ReLU activation, Dropout (0.2)
    - **Dense Layer 2:** 64 units, ReLU activation, Dropout (0.2)
    - **Dense Layer 3:** 32 units, ReLU activation
    - **Output Layer:** 1 unit (linear output for consumption prediction)
    - **Optimizer:** Adam (lr=0.001)
    - **Loss Function:** Mean Squared Error (MSE)

    ### Preprocessing & Leakage Prevention
    1. **Data Normalization:** `MinMaxScaler` fitted exclusively on the training split (70%) to ensure zero data leakage.
    2. **Sliding Window:** 168-hour input sequence mapped to 1-hour ahead target.
    3. **Chronological Splitting:** Data split into Train (70%), Validation (15%), and Held-Out Test (15%) sequentially without random shuffling.
    """)
